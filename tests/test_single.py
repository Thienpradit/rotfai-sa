import asyncio, pathlib
GAME=(pathlib.Path(__file__).resolve().parent.parent/'public'/'index.html').as_uri()
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        pg=await b.new_page(viewport={'width':400,'height':800},has_touch=True)
        errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto(GAME); await pg.wait_for_timeout(800)
        await pg.screenshot(path='/tmp/m0.png')
        await pg.fill('#name','ทดสอบ')
        await pg.click('#playInf'); await pg.wait_for_timeout(500)
        await pg.evaluate("""(()=>{player.safe=99;
          const s=rails[0];player.pts.forEach((q,i)=>{q.x=s.ax-s.ux*i*4;q.y=s.ay-s.uy*i*4});player.angle=Math.atan2(s.uy,s.ux);input.angle=player.angle;})()""")
        await pg.wait_for_timeout(300)
        out={}
        out['onRail']=await pg.evaluate("player.onRail")
        await pg.evaluate("(()=>{const p=portals[0];const h=player.pts[0];const dx=p.x-h.x-20,dy=p.y-h.y;for(const q of player.pts){q.x+=dx;q.y+=dy}player.angle=0;input.angle=0;player.tunCD=0;window._p1=portals[p.pair]})()")
        await pg.wait_for_timeout(300)
        out['tunnel']=await pg.evaluate("Math.hypot(player.pts[0].x-_p1.x,player.pts[0].y-_p1.y)<300")
        await pg.evaluate("(()=>{player.mass=150;player.follow();const st=stations[0];const sx=st.x+st.ox*45,sy=st.y+st.oy*45;const h=player.pts[0];const dx=sx-h.x,dy=sy-h.y;for(const q of player.pts){q.x+=dx;q.y+=dy}window._c0=prof.coins})()")
        await pg.wait_for_timeout(200)
        out['stationCoins']=await pg.evaluate("prof.coins-_c0")
        await pg.evaluate("(()=>{const h=player.pts[0];pups.push({x:h.x,y:h.y,type:'freeze',dead:false,ph:0});const e=worms.find(w=>!w.isP);for(const q of e.pts){q.x=h.x+200;q.y=h.y+200};e.safe=99;window._e=e})()")
        await pg.wait_for_timeout(200)
        out['frozen']=await pg.evaluate("_e.slow>0")
        await pg.evaluate("bossTimer=0"); await pg.wait_for_timeout(300)
        out['boss']=await pg.evaluate("!!bossActive&&bossActive.mass")
        await pg.screenshot(path='/tmp/m1.png')
        await pg.evaluate("bossActive.die(player)"); await pg.wait_for_timeout(100)
        out['bossTrack']=await pg.evaluate("prof.st.boss")
        await pg.evaluate("player.safe=0;player.die(null)"); await pg.wait_for_timeout(1800)
        out['overVisible']=await pg.evaluate("!document.getElementById('over').classList.contains('hidden')")
        out['rp']=await pg.evaluate("[prof.rp,roundRP,document.getElementById('rankOver').innerText]")
        await pg.screenshot(path='/tmp/m2.png')
        await pg.click('#toMenu'); await pg.evaluate("prof.coins=20000"); await pg.click('#bShop'); await pg.wait_for_timeout(200)
        btns=await pg.query_selector_all('#shopList .sbtn'); await btns[1].click(); await pg.wait_for_timeout(100)
        out['owned']=await pg.evaluate("JSON.stringify(prof.owned.loco)+prof.eq.loco")
        await pg.screenshot(path='/tmp/m3.png')
        await pg.click('#sheetClose'); await pg.click('#bMis'); await pg.wait_for_timeout(200); await pg.screenshot(path='/tmp/m4.png')
        await pg.click('#sheetClose'); await pg.click('#bAch'); await pg.wait_for_timeout(200); await pg.screenshot(path='/tmp/m5.png')
        await pg.click('#sheetClose'); await pg.evaluate("prof.rp=1234;showBest()"); await pg.click('#rankOpen'); await pg.wait_for_timeout(200); await pg.screenshot(path='/tmp/m6.png')
        out['rankSheet']=await pg.evaluate("document.getElementById('sheetTitle').textContent")
        out['nameSaved']=await pg.evaluate("localStorage.getItem('wormName')")
        await pg.click('#sheetClose'); await pg.click('#playTime'); await pg.evaluate("player.safe=99;timeLeft=60"); await pg.wait_for_timeout(500)
        out['AR']=await pg.evaluate("Math.round(AR)")
        await pg.screenshot(path='/tmp/m7.png')
        print(out); print('errors',errs)
        await b.close()
asyncio.run(main())
